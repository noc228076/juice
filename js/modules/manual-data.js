    var max = {};
    test.questions.forEach(function (q) {
      var per = {};
      q.o.forEach(function (op) {
        (op.s || []).forEach(function (p) {
          per[p[0]] = Math.max(per[p[0]] || 0, p[1]);
        });
      });
      Object.keys(per).forEach(function (k) { max[k] = (max[k] || 0) + per[k]; });
    });
    return max;
